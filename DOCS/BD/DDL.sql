-- Portal Escolar Sanico Teles - PostgreSQL
-- Execute em um banco vazio. Este arquivo cria a estrutura; DML.sql insere
-- somente dados de catálogo demonstrativos.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    foto_url TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_email_formato CHECK (position('@' IN email) > 1),
    CONSTRAINT ck_usuario_nome CHECK (length(trim(nome)) > 0)
);

CREATE TABLE turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(30) NOT NULL,
    ano_letivo SMALLINT NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    modalidade VARCHAR(30) NOT NULL DEFAULT 'Regular',
    CONSTRAINT uq_turma_ano_nome UNIQUE (ano_letivo, nome),
    CONSTRAINT ck_turma_ano CHECK (ano_letivo BETWEEN 2000 AND 2200),
    CONSTRAINT ck_turma_periodo CHECK (periodo IN ('Matutino', 'Vespertino', 'Noturno', 'Integral'))
);

-- Dados acadêmicos separados dos dados de autenticação. Uma conta de usuário
-- pode estar associada a no máximo um registro de aluno.
CREATE TABLE aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    turma_id BIGINT REFERENCES turma(id) ON DELETE SET NULL,
    numero_matricula VARCHAR(30) NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_aluno_matricula CHECK (length(trim(numero_matricula)) > 0)
);

CREATE TABLE disciplina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE horario_aula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id BIGINT NOT NULL REFERENCES turma(id) ON DELETE CASCADE,
    disciplina_id BIGINT NOT NULL REFERENCES disciplina(id) ON DELETE RESTRICT,
    dia_semana SMALLINT NOT NULL,
    numero_aula SMALLINT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    professor VARCHAR(120),
    CONSTRAINT ck_horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_horario_aula CHECK (numero_aula > 0),
    CONSTRAINT ck_horario_intervalo CHECK (hora_fim > hora_inicio),
    CONSTRAINT uq_horario_turma_dia_aula UNIQUE (turma_id, dia_semana, numero_aula)
);

CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT,
    categoria VARCHAR(50) NOT NULL DEFAULT 'Acadêmico',
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    horario TIME,
    local VARCHAR(200),
    publicado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_evento_intervalo CHECK (data_fim >= data_inicio),
    CONSTRAINT ck_evento_titulo CHECK (length(trim(titulo)) > 0)
);

-- Agenda pessoal. A cor é armazenada como hexadecimal (ex.: #bfdbfe).
CREATE TABLE compromisso_agenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    titulo VARCHAR(120) NOT NULL,
    descricao TEXT NOT NULL DEFAULT '',
    data_evento DATE NOT NULL,
    cor CHAR(7) NOT NULL DEFAULT '#bfdbfe',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_agenda_titulo CHECK (length(trim(titulo)) > 0),
    CONSTRAINT ck_agenda_cor CHECK (cor ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE categoria_clube (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL UNIQUE,
    cor_css VARCHAR(40),
    icone VARCHAR(20)
);

CREATE TABLE clube (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    categoria_id BIGINT NOT NULL REFERENCES categoria_clube(id) ON DELETE RESTRICT,
    nome VARCHAR(120) NOT NULL,
    lider VARCHAR(150),
    descricao TEXT NOT NULL,
    atividades TEXT NOT NULL DEFAULT '',
    dias VARCHAR(120) NOT NULL DEFAULT 'A confirmar',
    horario VARCHAR(80) NOT NULL DEFAULT 'A confirmar',
    local VARCHAR(200) NOT NULL DEFAULT 'A confirmar',
    imagem_url TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE proposta_clube (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    categoria_id BIGINT NOT NULL REFERENCES categoria_clube(id) ON DELETE RESTRICT,
    nome VARCHAR(120) NOT NULL,
    lider_sugerido VARCHAR(150) NOT NULL,
    local_sugerido VARCHAR(200) NOT NULL,
    horario_sugerido VARCHAR(120) NOT NULL,
    atividades TEXT NOT NULL,
    objetivo TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pendente',
    resposta_coordenacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_proposta_status CHECK (status IN ('Pendente', 'Aprovada', 'Recusada'))
);

CREATE TABLE inscricao_clube (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    clube_id BIGINT NOT NULL REFERENCES clube(id) ON DELETE RESTRICT,
    experiencia VARCHAR(30) NOT NULL,
    motivo TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pendente',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inscricao_usuario_clube UNIQUE (usuario_id, clube_id),
    CONSTRAINT ck_inscricao_experiencia CHECK (experiencia IN ('iniciante', 'intermediario-avancado')),
    CONSTRAINT ck_inscricao_status CHECK (status IN ('Pendente', 'Aprovada', 'Recusada'))
);

CREATE TABLE objeto_perdido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    local VARCHAR(200) NOT NULL,
    data_ocorrencia DATE NOT NULL,
    descricao TEXT NOT NULL,
    local_retirada VARCHAR(200) NOT NULL,
    foto_url TEXT,
    devolvido BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_objeto_categoria CHECK (categoria IN ('Material escolar', 'Roupas', 'Acessórios', 'Outros')),
    CONSTRAINT ck_objeto_nome CHECK (length(trim(nome)) > 0)
);

CREATE TABLE modalidade_cardapio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE cardapio_semanal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modalidade_id BIGINT NOT NULL REFERENCES modalidade_cardapio(id) ON DELETE RESTRICT,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    publicado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_cardapio_intervalo CHECK (data_fim >= data_inicio),
    CONSTRAINT uq_cardapio_modalidade_semana UNIQUE (modalidade_id, data_inicio)
);

CREATE TABLE refeicao_cardapio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cardapio_id BIGINT NOT NULL REFERENCES cardapio_semanal(id) ON DELETE CASCADE,
    dia_semana SMALLINT NOT NULL,
    almoco TEXT NOT NULL,
    lanche TEXT NOT NULL DEFAULT '',
    CONSTRAINT ck_refeicao_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT uq_refeicao_cardapio_dia UNIQUE (cardapio_id, dia_semana)
);

-- Índices para as consultas usuais e chaves estrangeiras.
CREATE INDEX ix_aluno_turma ON aluno(turma_id);
CREATE INDEX ix_horario_turma_dia ON horario_aula(turma_id, dia_semana, numero_aula);
CREATE INDEX ix_evento_datas ON evento(data_inicio, data_fim);
CREATE INDEX ix_agenda_usuario_data ON compromisso_agenda(usuario_id, data_evento);
CREATE INDEX ix_proposta_usuario_data ON proposta_clube(usuario_id, criado_em DESC);
CREATE INDEX ix_inscricao_clube_status ON inscricao_clube(clube_id, status);
CREATE INDEX ix_objeto_status_data ON objeto_perdido(devolvido, data_ocorrencia DESC);
CREATE INDEX ix_objeto_usuario ON objeto_perdido(usuario_id);
